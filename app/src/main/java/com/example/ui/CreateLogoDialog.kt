@OptIn(ExperimentalLayoutApi::class)
@Composable
fun CreateLogoDialog(
    initialEngine: String = "text_to_logo",
    initialIndustry: String = "Tech & AI",
    initialPrompt: String = "",
    onDismiss: () -> Unit,
    onSynthesize: (
        title: String,
        prompt: String,
        engine: String,
        industry: String,
        style: String,
        primaryColor: String,
        accentColor: String,
        badge: String,
        isPublic: Boolean
    ) -> Unit
) {
    var title by remember { mutableStateOf(if (initialPrompt.isNotBlank()) initialPrompt.take(20) else "") }
    var prompt by remember { mutableStateOf(initialPrompt) }
    var selectedEngine by remember { mutableStateOf(initialEngine) }
    var selectedIndustry by remember { mutableStateOf(initialIndustry) }
    var selectedStyle by remember { mutableStateOf("3D Emblem") }
    var selectedPaletteIdx by remember { mutableIntStateOf(0) }
    var shareToCommunity by remember { mutableStateOf(true) }
    var selectedVariant by remember { mutableIntStateOf(0) }
    var isSynthesizing by remember { mutableStateOf(false) }
    var variantsGenerated by remember { mutableStateOf(false) }

    val engines = listOf(
        "text_to_logo" to "Text to Logo",
        "sketch_ref" to "Sketch / Ref",
        "vector_trace" to "Vector Trace",
        "brand_kit" to "Brand Kit"
    )

    val industries = listOf("Tech & AI", "Gaming & Esports", "Coffee & Food", "Fashion", "Crypto & Web3", "Finance")
    val styles = listOf("3D Emblem", "Minimal", "Mascot", "Monogram", "Cyberpunk", "Abstract")

    val palettes = listOf(
        Triple("Cyber Cyan", "#00E5FF", "#A855F7"),
        Triple("Violet Aurora", "#8B5CF6", "#EC4899"),
        Triple("Neon Amber", "#F59E0B", "#EF4444"),
        Triple("Emerald Matrix", "#10B981", "#06B6D4"),
        Triple("Obsidian Gold", "#EAB308", "#6366F1")
    )

    val quickTokens = listOf(
        "Holographic neon", "Dynamic lighting", "Minimal vector", "Chrome metallic", "Geometric crystal", "Cyber shield"
    )

    Dialog(
        onDismissRequest = onDismiss,
        properties = DialogProperties(usePlatformDefaultWidth = false)
    ) {
        Surface(
            modifier = Modifier
                .fillMaxWidth(0.95f)
                .clip(RoundedCornerShape(24.dp))
                .background(SurfaceDark)
                .border(1.dp, BorderDark, RoundedCornerShape(24.dp)),
            color = SurfaceDark
        ) {
            Column(
                modifier = Modifier
                    .padding(20.dp)
                    .verticalScroll(rememberScrollState())
            ) {
                // Header
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.SpaceBetween,
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Box(
                            modifier = Modifier
                                .size(36.dp)
                                .clip(RoundedCornerShape(10.dp))
                                .background(Brush.linearGradient(listOf(NeonCyan, NeonPurple))),
                            contentAlignment = Alignment.Center
                        ) {
                            Icon(
                                imageVector = Icons.Default.AutoAwesome,
                                contentDescription = null,
                                tint = Color.Black,
                                modifier = Modifier.size(20.dp)
                            )
                        }
                        Spacer(modifier = Modifier.width(10.dp))
                        Column {
                            Text(
                                text = "Logo Neural Synthesis",
                                color = TextPrimary,
                                fontSize = 18.sp,
                                fontWeight = FontWeight.Bold
                            )
                            Text(
                                text = "Instant Brand Kit & Vector Compilation",
                                color = TextSecondary,
                                fontSize = 12.sp
                            )
                        }
                    }

                    IconButton(
                        onClick = onDismiss,
                        modifier = Modifier
                            .size(36.dp)
                            .clip(CircleShape)
                            .background(SurfaceCard)
                    ) {
                        Icon(
                            imageVector = Icons.Default.Close,
                            contentDescription = "Close",
                            tint = TextSecondary,
                            modifier = Modifier.size(18.dp)
                        )
                    }
                }

                Spacer(modifier = Modifier.height(18.dp))

                // Engine Selector
                Text("CREATIVE ENGINE", color = TextMuted, fontSize = 11.sp, fontWeight = FontWeight.Bold)
                Spacer(modifier = Modifier.height(8.dp))
                Row(
                    modifier = Modifier
                        .fillMaxWidth()
                        .horizontalScroll(rememberScrollState()),
                    horizontalArrangement = Arrangement.spacedBy(8.dp)
                ) {
                    engines.forEach { (key, label) ->
                        val isSelected = selectedEngine == key
                        Box(
                            modifier = Modifier
                                .clip(RoundedCornerShape(12.dp))
                                .background(if (isSelected) NeonPurple.copy(alpha = 0.25f) else SurfaceCard)
                                .border(1.dp, if (isSelected) NeonPurple else BorderDark, RoundedCornerShape(12.dp))
                                .clickable { selectedEngine = key }
                                .padding(horizontal = 14.dp, vertical = 8.dp)
                        ) {
                            Text(
                                text = label,
                                color = if (isSelected) Color.White else TextSecondary,
                                fontSize = 12.sp,
                                fontWeight = if (isSelected) FontWeight.Bold else FontWeight.Normal
                            )
                        }
                    }
                }

                Spacer(modifier = Modifier.height(16.dp))

                // Brand Name
                Text("BRAND NAME", color = TextMuted, fontSize = 11.sp, fontWeight = FontWeight.Bold)
                Spacer(modifier = Modifier.height(6.dp))
                OutlinedTextField(
                    value = title,
                    onValueChange = { title = it },
                    placeholder = { Text("e.g. Apex Dynamics, Kitsune Labs", color = TextMuted, fontSize = 13.sp) },
                    singleLine = true,
                    colors = OutlinedTextFieldDefaults.colors(
                        focusedTextColor = TextPrimary,
                        unfocusedTextColor = TextPrimary,
                        focusedBorderColor = NeonCyan,
                        unfocusedBorderColor = BorderDark,
                        focusedContainerColor = SurfaceCard,
                        unfocusedContainerColor = SurfaceCard
                    ),
                    shape = RoundedCornerShape(12.dp),
                    modifier = Modifier
                        .fillMaxWidth()
                        .testTag("brand_name_input")
                )

                Spacer(modifier = Modifier.height(14.dp))

                // Visual Prompt & Quick Tokens
                Text("PROMPT & ATTRIBUTES", color = TextMuted, fontSize = 11.sp, fontWeight = FontWeight.Bold)
                Spacer(modifier = Modifier.height(6.dp))
                OutlinedTextField(
                    value = prompt,
                    onValueChange = { prompt = it },
                    placeholder = { Text("Describe the emblem, typography style, dynamic lighting, or geometry...", color = TextMuted, fontSize = 13.sp) },
                    minLines = 2,
                    maxLines = 4,
                    colors = OutlinedTextFieldDefaults.colors(
                        focusedTextColor = TextPrimary,
                        unfocusedTextColor = TextPrimary,
                        focusedBorderColor = NeonCyan,
                        unfocusedBorderColor = BorderDark,
                        focusedContainerColor = SurfaceCard,
                        unfocusedContainerColor = SurfaceCard
                    ),
                    shape = RoundedCornerShape(12.dp),
                    modifier = Modifier
                        .fillMaxWidth()
                        .testTag("prompt_input")
                )

                Spacer(modifier = Modifier.height(8.dp))

                // Quick Tokens
                FlowRow(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.spacedBy(6.dp),
                    verticalArrangement = Arrangement.spacedBy(6.dp)
                ) {
                    quickTokens.forEach { token ->
                        Box(
                            modifier = Modifier
                                .clip(RoundedCornerShape(8.dp))
                                .background(SurfaceElevated)
                                .clickable {
                                    prompt = if (prompt.isBlank()) token else "$prompt, $token"
                                }
                                .padding(horizontal = 10.dp, vertical = 5.dp)
                        ) {
                            Text("+ $token", color = NeonCyan, fontSize = 11.sp)
                        }
                    }
                }

                Spacer(modifier = Modifier.height(14.dp))

                // Industry & Style
                Row(modifier = Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.spacedBy(10.dp)) {
                    Column(modifier = Modifier.weight(1f)) {
                        Text("INDUSTRY", color = TextMuted, fontSize = 11.sp, fontWeight = FontWeight.Bold)
                        Spacer(modifier = Modifier.height(6.dp))
                        Row(
                            modifier = Modifier
                                .fillMaxWidth()
                                .horizontalScroll(rememberScrollState()),
                            horizontalArrangement = Arrangement.spacedBy(6.dp)
                        ) {
                            industries.forEach { ind ->
                                val sel = selectedIndustry == ind
                                Box(
                                    modifier = Modifier
                                        .clip(RoundedCornerShape(8.dp))
                                        .background(if (sel) NeonCyan.copy(alpha = 0.2f) else SurfaceCard)
                                        .border(1.dp, if (sel) NeonCyan else BorderDark, RoundedCornerShape(8.dp))
                                        .clickable { selectedIndustry = ind }
                                        .padding(horizontal = 10.dp, vertical = 6.dp)
                                ) {
                                    Text(ind, color = if (sel) NeonCyan else TextSecondary, fontSize = 11.sp)
                                }
                            }
                        }
                    }
                }

                Spacer(modifier = Modifier.height(12.dp))

                // Style
                Text("STYLE", color = TextMuted, fontSize = 11.sp, fontWeight = FontWeight.Bold)
                Spacer(modifier = Modifier.height(6.dp))
                Row(
                    modifier = Modifier
                        .fillMaxWidth()
                        .horizontalScroll(rememberScrollState()),
                    horizontalArrangement = Arrangement.spacedBy(6.dp)
                ) {
                    styles.forEach { st ->
                        val sel = selectedStyle == st
                        Box(
                            modifier = Modifier
                                .clip(RoundedCornerShape(8.dp))
                                .background(if (sel) NeonViolet.copy(alpha = 0.25f) else SurfaceCard)
                                .border(1.dp, if (sel) NeonViolet else BorderDark, RoundedCornerShape(8.dp))
                                .clickable { selectedStyle = st }
                                .padding(horizontal = 10.dp, vertical = 6.dp)
                        ) {
                            Text(st, color = if (sel) Color.White else TextSecondary, fontSize = 11.sp)
                        }
                    }
                }

                Spacer(modifier = Modifier.height(14.dp))

                // Color Palette
                Text("COLOR PALETTE", color = TextMuted, fontSize = 11.sp, fontWeight = FontWeight.Bold)
                Spacer(modifier = Modifier.height(6.dp))
                Row(
                    modifier = Modifier
                        .fillMaxWidth()
                        .horizontalScroll(rememberScrollState()),
                    horizontalArrangement = Arrangement.spacedBy(10.dp)
                ) {
                    palettes.forEachIndexed { index, (name, pCol, aCol) ->
                        val sel = selectedPaletteIdx == index
                        val p = Color(android.graphics.Color.parseColor(pCol))
                        val a = Color(android.graphics.Color.parseColor(aCol))

                        Row(
                            modifier = Modifier
                                .clip(RoundedCornerShape(10.dp))
                                .background(if (sel) SurfaceElevated else SurfaceCard)
                                .border(1.dp, if (sel) NeonCyan else BorderDark, RoundedCornerShape(10.dp))
                                .clickable { selectedPaletteIdx = index }
                                .padding(horizontal = 10.dp, vertical = 6.dp),
                            verticalAlignment = Alignment.CenterVertically
                        ) {
                            Box(
                                modifier = Modifier
                                    .size(14.dp)
                                    .clip(CircleShape)
                                    .background(p)
                            )
                            Spacer(modifier = Modifier.width(4.dp))
                            Box(
                                modifier = Modifier
                                    .size(14.dp)
                                    .clip(CircleShape)
                                    .background(a)
                            )
                            Spacer(modifier = Modifier.width(6.dp))
                            Text(name, color = if (sel) TextPrimary else TextSecondary, fontSize = 11.sp)
                        }
                    }
                }

                Spacer(modifier = Modifier.height(18.dp))

                // Synthesized Variants Preview Section
                if (variantsGenerated) {
                    Text(
                        text = "4 NEURAL VARIANTS GENERATED",
                        color = NeonCyan,
                        fontSize = 11.sp,
                        fontWeight = FontWeight.Bold
                    )
                    Spacer(modifier = Modifier.height(10.dp))

                    Row(
                        modifier = Modifier.fillMaxWidth(),
                        horizontalArrangement = Arrangement.spacedBy(8.dp)
                    ) {
                        val (_, curP, curA) = palettes[selectedPaletteIdx]
                        listOf("Variant A (Primary)", "Variant B (Alternate)", "Variant C (Monochrome)", "Variant D (Inverted)").forEachIndexed { idx, label ->
                            val isSel = selectedVariant == idx
                            Column(
                                modifier = Modifier
                                    .weight(1f)
                                    .clip(RoundedCornerShape(12.dp))
                                    .background(if (isSel) SurfaceElevated else SurfaceCard)
                                    .border(1.5.dp, if (isSel) NeonCyan else BorderDark, RoundedCornerShape(12.dp))
                                    .clickable { selectedVariant = idx }
                                    .padding(6.dp),
                                horizontalAlignment = Alignment.CenterHorizontally
                            ) {
                                Box(
                                    modifier = Modifier
                                        .size(56.dp)
                                        .clip(RoundedCornerShape(8.dp))
                                ) {
                                    LogoGraphic(
                                        title = if (idx == 0) title else "$title $idx",
                                        style = selectedStyle,
                                        primaryColorHex = if (idx == 2) "#E2E8F0" else curP,
                                        accentColorHex = if (idx == 2) "#94A3B8" else curA,
                                        modifier = Modifier.fillMaxSize()
                                    )
                                }
                                Spacer(modifier = Modifier.height(4.dp))
                                Text(
                                    text = "V${idx + 1}",
                                    color = if (isSel) NeonCyan else TextSecondary,
                                    fontSize = 11.sp,
                                    fontWeight = FontWeight.Bold
                                )
                            }
                        }
                    }

                    Spacer(modifier = Modifier.height(14.dp))

                    // Public toggle
                    Row(
                        modifier = Modifier
                            .fillMaxWidth()
                            .clip(RoundedCornerShape(12.dp))
                            .background(SurfaceCard)
                            .clickable { shareToCommunity = !shareToCommunity }
                            .padding(12.dp),
                        verticalAlignment = Alignment.CenterVertically,
                        horizontalArrangement = Arrangement.SpaceBetween
                    ) {
                        Column {
                            Text("Publish to Community Feed", color = TextPrimary, fontSize = 13.sp, fontWeight = FontWeight.SemiBold)
                            Text("Share with creators and collect remixes & likes", color = TextSecondary, fontSize = 11.sp)
                        }
                        Box(
                            modifier = Modifier
                                .size(24.dp)
                                .clip(RoundedCornerShape(6.dp))
                                .background(if (shareToCommunity) NeonCyan else SurfaceElevated),
                            contentAlignment = Alignment.Center
                        ) {
                            if (shareToCommunity) {
                                Icon(Icons.Default.Check, contentDescription = null, tint = Color.Black, modifier = Modifier.size(16.dp))
                            }
                        }
                    }
                }

                Spacer(modifier = Modifier.height(20.dp))

                // Actions: Synthesize or Save
                if (!variantsGenerated) {
                    Button(
                        onClick = {
                            isSynthesizing = true
                            variantsGenerated = true
                            isSynthesizing = false
                        },
                        colors = ButtonDefaults.buttonColors(
                            containerColor = NeonCyan,
                            contentColor = Color.Black
                        ),
                        shape = RoundedCornerShape(14.dp),
                        modifier = Modifier
                            .fillMaxWidth()
                            .height(50.dp)
                            .testTag("synthesize_button")
                    ) {
                        Row(verticalAlignment = Alignment.CenterVertically) {
                            Icon(Icons.Default.Bolt, contentDescription = null, tint = Color.Black, modifier = Modifier.size(20.dp))
                            Spacer(modifier = Modifier.width(8.dp))
                            Text("Synthesize 4 Logo Variants (⚡ 2 Credits)", fontWeight = FontWeight.Bold, fontSize = 14.sp)
                        }
                    }
                } else {
                    Button(
                        onClick = {
                            val (_, curP, curA) = palettes[selectedPaletteIdx]
                            onSynthesize(
                                title.ifBlank { "Apex Cyber" },
                                prompt.ifBlank { "$selectedStyle logo for $selectedIndustry" },
                                selectedEngine,
                                selectedIndustry,
                                selectedStyle,
                                curP,
                                curA,
                                "VECTOR READY",
                                shareToCommunity
                            )
                        },
                        colors = ButtonDefaults.buttonColors(
                            containerColor = NeonPurple,
                            contentColor = Color.White
                        ),
                        shape = RoundedCornerShape(14.dp),
                        modifier = Modifier
                            .fillMaxWidth()
                            .height(50.dp)
                            .testTag("save_project_button")
                    ) {
                        Row(verticalAlignment = Alignment.CenterVertically) {
                            Icon(Icons.Default.AutoAwesome, contentDescription = null, modifier = Modifier.size(20.dp))
                            Spacer(modifier = Modifier.width(8.dp))
                            Text("Save Selected Variant to Cloud", fontWeight = FontWeight.Bold, fontSize = 14.sp)
                        }
                    }
                }
            }
        }
    }
}
